/* pull window.__out from a finished prep page on the debug port and write the outputs */
import fs from 'node:fs';
const ROOT=new URL('..',import.meta.url).pathname, port=process.argv[2]||9334;
const j=await (await fetch(`http://127.0.0.1:${port}/json`)).json();
const pg=j.find(x=>x.type==='page'&&x.url.includes('prep.html'));
const ws=new WebSocket(pg.webSocketDebuggerUrl); await new Promise(r=>ws.onopen=r);
const res=await new Promise(r=>{ ws.onmessage=e=>{const m=JSON.parse(e.data); if(m.id===1) r(m.result);};
  ws.send(JSON.stringify({id:1,method:'Runtime.evaluate',params:{expression:'JSON.stringify(window.__out)',returnByValue:true}})); });
const out=JSON.parse(res.result.value);
fs.writeFileSync(ROOT+'assets/targets.mind',Buffer.from(out.targets,'base64'));
fs.writeFileSync(ROOT+'tools/mean-target.png',Buffer.from(out.meanPNG.split(',')[1],'base64'));
fs.writeFileSync(ROOT+'signatures.js','/* generated by tools/prep.html — colour signature per number side, GRID order */\nexport const SIGNATURES='+JSON.stringify(out.sig)+';\n');
console.log('written', out.sig.length, 'signatures', JSON.stringify(out.features)); process.exit(0);
